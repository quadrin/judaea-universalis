import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const events = new EventTarget();
const serviceWorker = new EventTarget();
const messages = [];
let registrations = 0, prompted = 0;
const registration = { active: { postMessage(message) { messages.push(message); } } };
serviceWorker.register = async () => { registrations++; return registration; };
serviceWorker.ready = Promise.resolve(registration);
serviceWorker.controller = null;
globalThis.window = { addEventListener: (...args) => events.addEventListener(...args), matchMedia: () => ({ matches: false }) };
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { serviceWorker } });
globalThis.document = { readyState: 'complete' };
globalThis.location = { protocol: 'https:' };
globalThis.__JU_OFFLINE__ = false;
const source = await fs.readFile(new URL('../../js/ui/install.js', import.meta.url), 'utf8');
const app = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
app.initAppSupport();
app.initAppSupport();
await new Promise(setImmediate);
assert.equal(registrations, 1, 'Register once even if the UI is rebuilt');
assert.equal(messages.at(-1).type, 'ju-precache');
assert.equal(app.appState().ready, false);
function report(data) {
  const event = new Event('message');
  Object.defineProperty(event, 'data', { value: data });
  serviceWorker.dispatchEvent(event);
}
report({ type: 'ju-precached', count: 250 });
assert.equal(app.appState().ready, false, 'Old count-only workers cannot claim readiness');
report({ type: 'ju-precached', complete: false, missingCount: 1 });
assert.equal(app.appState().ready, false);
assert.match(app.offlineStatus(), /missing/);
report({ type: 'ju-precached', complete: true, count: 250 });
assert.equal(app.appState().ready, true);
assert.equal(app.offlineStatus(), 'Ready to play offline');
const prompt = new Event('beforeinstallprompt', { cancelable: true });
prompt.prompt = async () => { prompted++; };
prompt.userChoice = Promise.resolve({ outcome: 'accepted' });
events.dispatchEvent(prompt);
assert.equal(prompt.defaultPrevented, true);
assert.equal(app.appState().canInstall, true);
assert.equal(prompted, 0, 'Installation must wait for an explicit click');
events.dispatchEvent(new Event('appinstalled'));
assert.equal(app.appState().installed, true);
assert.equal(app.appState().canInstall, false);
const before = messages.length;
events.dispatchEvent(new Event('online'));
assert.equal(messages.length, before + 1, 'Reconnect asks for another offline check');
globalThis.__JU_OFFLINE__ = true;
const offline = await import('data:text/javascript;base64,' + Buffer.from(source + '\n// standalone copy').toString('base64'));
offline.initAppSupport();
assert.equal(registrations, 1, 'The standalone HTML must not register a service worker');
assert.equal(offline.appState().ready, true);
console.log('Install-event capture, explicit-click requirement, cache-readiness status, reconnect and standalone mode passed.');
