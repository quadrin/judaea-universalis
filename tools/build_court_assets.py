#!/usr/bin/env python3
"""Embed the checked-in generated court images for web and portable builds."""
from pathlib import Path
import base64
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'icons' / 'court-generated'
entries = json.loads((SOURCE / 'manifest.json').read_text())['assets']
# The checked-in JS modules are the canonical compressed source images.
# Recover local WebP files when rebuilding from a clean checkout.
for module in sorted((ROOT / 'js' / 'ui').glob('generated_court_assets_*.js')):
    content = module.read_text()
    packed = json.loads(content.split('export default ',1)[1].rsplit(';',1)[0])
    for name,uri in packed.items():
        target = SOURCE / (name + '.webp')
        if not target.exists():
            target.write_bytes(base64.b64decode(uri.split(',',1)[1]))
groups = []
for start in range(0, len(entries), 8):
    chunk = {}
    for entry in entries[start:start + 8]:
        name = entry['id']
        if not re.fullmatch(r'[a-z0-9-]+', name):
            raise ValueError('Invalid asset identifier')
        data = (SOURCE / (name + '.webp')).read_bytes()
        if data[:4] != b'RIFF' or data[8:12] != b'WEBP':
            raise ValueError('Expected local WebP image: ' + name)
        chunk[name] = 'data:image/webp;base64,' + base64.b64encode(data).decode()
    index = len(groups)
    path = f'generated_court_assets_{index:02}.js'
    (ROOT / 'js' / 'ui' / path).write_text('// Generated by tools/build_court_assets.py.\nexport default ' + json.dumps(chunk, separators=(',', ':')) + ';\n')
    groups.append(path)

imports = '\n'.join(f"import group{i} from './{name}';" for i, name in enumerate(groups))
sources = ','.join(f'...group{i}' for i in range(len(groups)))
mapping = {tag: e['id'] for e in entries for tag in e['tags']}
notes = {e['id']:e['subject'] for e in entries}
if len(mapping) != sum(len(e['tags']) for e in entries):
    raise ValueError('A court has more than one generated master')
module = imports + '\nconst images = {' + sources + '};\n'
module += 'const descriptions = ' + json.dumps(notes, separators=(',', ':')) + ';\n'
module += 'export const GENERATED_COURT_ASSETS = Object.freeze(' + json.dumps(mapping, sort_keys=True, separators=(',', ':')) + ');\n'
module += '''
export function enrichGeneratedCourtStandards(flags) {
  for (const [tag, id] of Object.entries(GENERATED_COURT_ASSETS)) {
    const original = flags[tag];
    if (!original || !images[id]) throw new Error('Missing court image: ' + tag);
    const originalMotifNote = original.note || '';
    flags[tag] = {...original, viewBox:'0 0 192 192', detailed:true, imageAsset:id,
      originalMotifNote, note:descriptions[id] + ' Generated game artwork interpreting the established motif; colours and composition are illustrative.',
      body:`<rect width="192" height="192" fill="${original.fieldColor}"/><g data-emblem="${original.emblem}" data-generated-art="${id}"><image x="7" y="7" width="178" height="178" preserveAspectRatio="xMidYMid meet" href="${images[id]}"/></g>`};
  }
}
'''
(ROOT / 'js' / 'ui' / 'generated_standards.js').write_text(module)
print(json.dumps({'assets':len(entries),'courts':len(mapping),'modules':len(groups) + 1}))
