#!/usr/bin/env node
// Package generated court masters. No generation credentials or network needed.
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2), option=name=>{const i=args.indexOf(name);return i<0?null:args[i+1];};
const recordsDir=option('--records'), jobsPath=option('--jobs');
const target=path.join(root,'icons/court-flat');
await fs.mkdir(target,{recursive:true});
let entries;
if(recordsDir&&jobsPath){
 const require=createRequire(import.meta.url);
 const sharp=require(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES?path.join(process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES,'sharp'):'sharp');
 const jobs=JSON.parse(await fs.readFile(jobsPath,'utf8'));
 entries=[];
 for(const job of jobs){
  let record;
  try{record=JSON.parse(await fs.readFile(path.join(recordsDir,job.id+'.json'),'utf8'));}
  catch(error){if(args.includes('--allow-partial'))continue;throw new Error('Missing generated master: '+job.id);}
  const source=await fs.readFile(record.source_png),sourceSHA=createHash('sha256').update(source).digest('hex');
  const cacheFile=path.join(target,job.id+'.meta.json');
  try{
   const previous=JSON.parse(await fs.readFile(cacheFile,'utf8'));
   if(previous.source_sha256===sourceSHA){await fs.access(path.join(target,job.id+'.webp'));entries.push({...previous,prompt:record.prompt||job.prompt,subject:job.subject});continue;}
  }catch{}
  const meta=await sharp(source).metadata();
  const stats=await sharp(source).stats();
  if(!meta.hasAlpha||stats.channels.at(-1).min!==0||stats.channels.at(-1).max<250){
   if(args.includes('--allow-partial')){console.error('Needs transparency repair: '+job.id);continue;}
   throw new Error('Expected true transparent master: '+job.id);
  }
  // Format/size conversion for the game; the generated contours remain intact.
  const data=await sharp(source).resize(640,640,{fit:'inside',withoutEnlargement:true}).webp({quality:92,alphaQuality:100,effort:4}).toBuffer();
  await fs.writeFile(path.join(target,job.id+'.webp'),data);
  const output=await sharp(data).metadata();
  const entry={id:job.id,tags:job.tags,subject:job.subject,prompt:record.prompt||job.prompt,
   source_png:path.basename(record.source_png),source_sha256:sourceSHA,
   sha256:createHash('sha256').update(data).digest('hex'),bytes:data.length,width:output.width,height:output.height,transparent:true};
  await fs.writeFile(cacheFile,JSON.stringify(entry));entries.push(entry);
 }
 const manifest={created:'2026-10-30',method:'Generated individually with the built-in image-generation tool; flat local colours and detailed heraldic linework',
  style_reference:'exec-ea4f1f3b-f5a8-41a9-a88c-da5a91787621.png',assets:entries};
 await fs.writeFile(path.join(target,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
}else{
 entries=JSON.parse(await fs.readFile(path.join(target,'manifest.json'),'utf8')).assets;
 // Embedded modules are the canonical compressed originals in a clean checkout.
 for(const file of (await fs.readdir(path.join(root,'js/ui'))).filter(f=>/^flat_generated_assets_\d+\.js$/.test(f)).sort()){
  const text=await fs.readFile(path.join(root,'js/ui',file),'utf8');
  const images=JSON.parse(text.split('export default ')[1].trim().replace(/;$/,''));
  for(const [id,uri] of Object.entries(images))await fs.writeFile(path.join(target,id+'.webp'),Buffer.from(uri.split(',')[1],'base64'));
 }
}
const modules=[];
for(let start=0;start<entries.length;start+=6){
 const images={};
 for(const entry of entries.slice(start,start+6)){
  const data=await fs.readFile(path.join(target,entry.id+'.webp'));
  if(createHash('sha256').update(data).digest('hex')!==entry.sha256)throw new Error('Image checksum mismatch: '+entry.id);
  images[entry.id]='data:image/webp;base64,'+data.toString('base64');
 }
 const name=`flat_generated_assets_${String(modules.length).padStart(2,'0')}.js`;
 await fs.writeFile(path.join(root,'js/ui',name),'// Generated by tools/build_flat_court_assets.mjs.\nexport default '+JSON.stringify(images)+';\n');
 modules.push(name);
}
const mapping=Object.fromEntries(entries.flatMap(e=>e.tags.map(tag=>[tag,e.id])));
if(Object.keys(mapping).length!==entries.reduce((n,e)=>n+e.tags.length,0))throw new Error('Duplicate court assignment');
await fs.writeFile(path.join(root,'js/ui/flat_generated_images.js'),modules.map((name,i)=>`import group${i} from './${name}';`).join('\n')
 +'\nexport const FLAT_GENERATED_IMAGES={'+modules.map((_,i)=>'...group'+i).join(',')+'};\n'
 +'export const FLAT_GENERATED_COURTS=Object.freeze('+JSON.stringify(mapping)+');\n');
console.log(JSON.stringify({assets:entries.length,courts:Object.keys(mapping).length,modules:modules.length,totalBytes:entries.reduce((n,e)=>n+e.bytes,0)}));
