#!/usr/bin/env python3
"""Embed attributed flag vectors without redrawing their devices.

Only passive SVG geometry survives; editorial metadata is removed. The complete
source flag is fitted inside a square chip without changing its aspect ratio.
"""
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / 'icons/source/national-flags'
SVG = 'http://www.w3.org/2000/svg'
XLINK = 'http://www.w3.org/1999/xlink'
ALLOWED = {'svg', 'g', 'path', 'rect', 'circle', 'ellipse', 'polygon',
           'polyline', 'line', 'use', 'defs', 'clipPath', 'linearGradient',
           'radialGradient', 'stop'}
DISCARD = {'metadata', 'title', 'desc', 'namedview'}
ET.register_namespace('', SVG)
ET.register_namespace('xlink', XLINK)


def clean(node):
    name = node.tag.split('}')[-1]
    if name in DISCARD or not node.tag.startswith('{' + SVG + '}'):
        return None
    if name not in ALLOWED:
        raise ValueError(f'Unexpected SVG element {name}')
    out = ET.Element('{' + SVG + '}' + name)
    for key, value in node.attrib.items():
        attr = key.split('}')[-1]
        if key.startswith('{') and not key.startswith('{' + XLINK + '}'):
            continue
        if attr.lower().startswith('on'):
            raise ValueError('Event handler in source SVG')
        if attr in {'href', 'src'} and not value.startswith('#'):
            raise ValueError('External resource in source SVG')
        if re.search(r'url\(\s*[\'"]?(?!#)', value):
            raise ValueError('External paint resource in source SVG')
        out.set(key, value)
    for child in node:
        kept = clean(child)
        if kept is not None:
            out.append(kept)
    return out


def encode(entry):
    data = (SOURCES / (entry['tag'] + '.svg')).read_bytes()
    src = clean(ET.fromstring(data))
    box = src.get('viewBox')
    if box is None:
        width = float(src.get('width'))
        height = float(src.get('height'))
        box = f'0 0 {width:g} {height:g}'
    _, _, width, height = map(float, box.replace(',', ' ').split())
    fitted_width = min(96, 96 * width / height)
    fitted_height = min(96, 96 * height / width)
    for key in ('width', 'height', 'x', 'y', 'version', 'id'):
        src.attrib.pop(key, None)
    src.set('viewBox', box)
    src.set('x', f'{(96-fitted_width)/2:g}')
    src.set('y', f'{(96-fitted_height)/2:g}')
    src.set('width', f'{fitted_width:g}')
    src.set('height', f'{fitted_height:g}')
    body = ET.tostring(src, encoding='unicode').replace(' />', '/>')
    return {'viewBox': '0 0 96 96', 'flatBanner': True,
            'nationalFlag': True, 'emblem': 'national-flag-' + entry['tag'],
            'source': [entry['title'], entry['source']],
            'note': entry['note'], 'detailed': False,
            'sourceSHA256': hashlib.sha256(data).hexdigest(),
            'body': '<g data-national-flag="' + entry['tag'] + '">' + body + '</g>'}


def main():
    entries = json.loads((SOURCES / 'manifest.json').read_text())
    flags = {entry['tag']: encode(entry) for entry in entries}
    # Attribution is also embedded in the offline game, which has no file server.
    credits = [{k: v for k, v in entry.items() if k != 'note'} for entry in entries]
    output = '// Generated by tools/build_national_flags.py; edit the attributed source SVGs.\n'
    output += 'export const NATIONAL_FLAG_CREDITS = ' + json.dumps(credits, ensure_ascii=False, separators=(',', ':')) + ';\n'
    output += 'export const FLAG_ICONS_LICENSE = ' + json.dumps((SOURCES / 'LICENSE-flag-icons.txt').read_text()) + ';\n'
    output += 'export const AUTHENTIC_NATIONAL_FLAGS = ' + json.dumps(flags, ensure_ascii=False, separators=(',', ':')) + ';\n'
    (ROOT / 'js/ui/authentic_national_flags.js').write_text(output)
    print(f'Embedded {len(flags)} complete national and faction flag vectors')


if __name__ == '__main__':
    main()
